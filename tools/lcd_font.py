glyphs = {}
for line in G.strip("\n").split("\n"):
    ch, rows = line[0], line[3:].split()
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), line
    glyphs[ch] = rows
assert sorted(map(ord, glyphs)) == list(range(32, 127)), "missing glyphs"
if sys.argv[1] == "header":
    out = ["// 5x7 dot-matrix character set in the style of the HD44780 LCD controller, ASCII 32-126.",
           "// Generated from tools/lcd_font.py -- one entry per character, one 5-bit row per line, MSB left.",
           "#pragma once", "", "#include <cstdint>", "", "namespace glide90::ui", "{", "",
           "inline constexpr uint8_t kLcdFont[95][7] = {"]
    for c in range(32, 127):
        rows = glyphs[chr(c)]
        out.append("    { " + ", ".join(f"0b{r}" for r in rows) + " }, // " + repr(chr(c)))
    out += ["};", "", "} // namespace glide90::ui", ""]
    open(sys.argv[2], "w").write("\n".join(out))
else:
    import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    text = [chr(c) for c in range(32, 127)]
    cols = 24; rowsN = (len(text) + cols - 1) // cols
    img = np.zeros((rowsN * 9, cols * 6))
    for i, ch in enumerate(text):
        r, c = divmod(i, cols)
        for y, row in enumerate(glyphs[ch]):
            for x, b in enumerate(row):
                img[r * 9 + y + 1, c * 6 + x] = int(b)
    plt.figure(figsize=(14, 5)); plt.imshow(img, cmap="gray_r", interpolation="nearest"); plt.axis("off")
    plt.savefig(sys.argv[2], dpi=100, bbox_inches="tight")
